import { loadEnv, type Plugin } from "vite";
import { defineConfig } from "vitest/config";
import react from "@vitejs/plugin-react";
import { VitePWA } from "vite-plugin-pwa";

// Dev only: serves /api/detect from the same handler Vercel runs, with keys from .env.local (git-ignored).
function devDetectApi(): Plugin {
  return {
    name: "growsafe-dev-detect",
    apply: "serve",
    configureServer(server) {
      const env = loadEnv("development", process.cwd(), "");
      server.middlewares.use("/api/detect", (req, res) => {
        const chunks: Buffer[] = [];
        req.on("data", (c: Buffer) => chunks.push(c));
        req.on("end", () => {
          void (async () => {
            try {
              const mod = (await server.ssrLoadModule(
                "/api/detect.ts",
              )) as typeof import("./api/detect");
              const host = req.headers.host ?? "localhost";
              const request = new Request(`http://${host}/api/detect`, {
                method: req.method,
                headers: req.headers as Record<string, string>,
                body: req.method === "POST" ? Buffer.concat(chunks) : undefined,
              });
              const out = await mod.POST(request, { env });
              res.statusCode = out.status;
              out.headers.forEach((v, k) => res.setHeader(k, v));
              res.end(Buffer.from(await out.arrayBuffer()));
            } catch {
              res.statusCode = 500;
              res.end('{"error":"provider_error"}');
            }
          })();
        });
      });
    },
  };
}

// Installable PWA: manifest + service worker generated by vite-plugin-pwa.
export default defineConfig({
  plugins: [
    react(),
    devDetectApi(),
    VitePWA({
      registerType: "autoUpdate",
      injectRegister: false, // registered from src/main.tsx so the native app can skip it
      includeAssets: ["icon-192.png", "icon-512.png"],
      manifest: {
        name: "GrowSafe",
        short_name: "GrowSafe",
        description: "A free child-safety planner.",
        display: "standalone",
        start_url: "/",
        scope: "/",
        background_color: "#f4f5f7",
        theme_color: "#f4f5f7",
        icons: [
          { src: "/icon-192.png", sizes: "192x192", type: "image/png" },
          { src: "/icon-512.png", sizes: "512x512", type: "image/png" },
        ],
      },
    }),
  ],
  test: {
    environment: "jsdom",
    setupFiles: ["./src/test-setup.ts"],
    include: ["src/**/*.test.{ts,tsx}"],
  },
});
